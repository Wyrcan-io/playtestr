"""Bind pristine Git source and the backend-generated version separately."""
import json

from next20_check import DOC, RAW
from readiness_evidence import immutable_json, sha256


def main():
    package=DOC/'pdm';target=RAW/'active/pdm';source=target/'src'
    provenance=json.loads((package/'source-provenance.json').read_text())
    expected=provenance['files']
    actual={p.relative_to(source).as_posix():sha256(p) for p in source.rglob('*') if p.is_file()}
    generated={'src/pdm/VERSION','.pdm-build/.gitignore','.pdm-build/_editable_impl_pdm.pth'}
    if set(actual)!=set(expected)|generated:
        raise ValueError('unexpected source inventory: extra='+repr(sorted(set(actual)-set(expected)-generated))+' missing='+repr(sorted(set(expected)-set(actual))))
    if any(actual[name]!=digest for name,digest in expected.items()):raise ValueError('primary Git source changed')
    if (source/'src/pdm/VERSION').read_bytes()!=b'0.0.0+pin.201bdc719c15\n':raise ValueError('unexpected backend version bytes')
    if (source/'.pdm-build/.gitignore').read_bytes()!=b'*\r\n':raise ValueError('unexpected generated ignore bytes')
    pth=source/'.pdm-build/_editable_impl_pdm.pth'
    if pth.read_text().splitlines()!=[str(source/'src')]:raise ValueError('editable path is not the exact owned source; imports forbidden')
    immutable_json(package/'runtime-generated-source.json',dict(schema_version=1,
        primary_source_provenance_sha256=sha256(package/'source-provenance.json'),
        primary_git_files=len(expected),primary_git_files_unchanged=True,
        generated_files={name:dict(sha256=actual[name],utf8=(source/name).read_bytes().decode('utf-8')) for name in sorted(generated)},
        scope='Ordinary editable backend generated this native-text version file; it is not a primary Git blob. Native profiles must independently bind their actual generated bytes.',
        runtime_sha256=sha256(target/'runtime.json'),build_sha256=sha256(target/'build.json'),
        historical_screens_complete=False,project_admission=False))
    print('Verified all primary Git blobs and separately bound generated version bytes; no admission.')


if __name__=='__main__':main()
