"""Bind the explicitly reviewed Hatch backend and native-wheel hook scope."""
import hashlib
import json
import zipfile

from next20_check import DOC,RAW
from readiness_evidence import immutable_json,sha256


def main():
    target=RAW/'active/hatch';inputs=target/'wheel-review-inputs/index-v2.json'
    rows=json.loads(inputs.read_text())['wheels'];approved={};sources={}
    reviewed={
        'setuptools':['distutils-precedence.pth','_distutils_hack/__init__.py'],
        'hatch-vcs':['hatch_vcs/hooks.py','hatch_vcs/version_source.py','hatch_vcs/build_hook.py'],
        'hatchling':['hatchling/build.py','hatchling/builders/wheel.py','hatchling/builders/constants.py','hatchling/builders/plugin/interface.py','hatchling/plugin/manager.py'],
        'setuptools-scm':['setuptools_scm/_get_version.py'],
        'vcs-versioning':['vcs_versioning/_get_version_impl.py','vcs_versioning/_overrides.py','vcs_versioning/overrides.py'],
        'editables':['editables/__init__.py'],
        'uv':['uv/__init__.py','uv/_find_uv.py'],
    }
    for row in rows:
        path=target/'wheels'/row['wheel']
        if sha256(path)!=row['sha256']:raise ValueError('reviewed wheel changed')
        with zipfile.ZipFile(path) as archive:
            name=row['name'].lower().replace('_','-')
            for member in reviewed.get(name,[]):sources[row['wheel']+'/'+member]=hashlib.sha256(archive.read(member)).hexdigest()
            hooks=row['hooks']
            if hooks:
                scripts={n:d for n,d in hooks.items() if '.data/scripts/' in n};startup={n:d for n,d in hooks.items() if n.endswith('.pth')}
                if name=='setuptools':
                    if scripts or set(startup)!={'distutils-precedence.pth'}:raise ValueError('unexpected setuptools hooks')
                    expected=b"import os; var = 'SETUPTOOLS_USE_DISTUTILS'; enabled = os.environ.get(var, 'local') == 'local'; enabled and __import__('_distutils_hack').add_shim(); \n"
                    if archive.read('distutils-precedence.pth')!=expected:raise ValueError('reviewed setuptools startup text changed')
                elif name=='uv':
                    if startup or {n.rsplit('/',1)[1] for n in scripts}!={'uv.exe','uvw.exe','uvx.exe'}:raise ValueError('unexpected native uv scripts')
                    for member in scripts:
                        data=archive.read(member)
                        if not data.startswith(b'MZ') or hashlib.sha256(data).hexdigest()!=scripts[member]:raise ValueError('native review identity differs')
                else:raise ValueError('unreviewed wheel startup/native hook')
                approved[row['wheel']]=dict(wheel_sha256=row['sha256'],scripts=scripts,startup_hooks=startup)
    immutable_json(target/'wheel-script-approval.json',approved)
    immutable_json(DOC/'hatch/backend-hook-review.json',dict(schema_version=1,primary_inputs_sha256=sha256(inputs),
        reviewed_member_sha256=sources,wheel_script_approval_sha256=sha256(target/'wheel-script-approval.json'),
        decisions=[
            'Trust retained primary-release wheel identities for owned offline installation; this is not a security sandbox or a source-built native uv claim.',
            'Setuptools .pth imports only the reviewed _distutils_hack and installs its distutils meta finder; no network or subprocess launch in this startup path.',
            'uv provides three primary-bound Windows PE scripts. Installation copies them only; uv execution and all environment/Python-download routes are excluded.',
            'hatch-vcs loads only its reviewed registered hooks; configured version/build hooks call setuptools_scm get_version/dump_version. No custom project build scripts are configured.',
            'SETUPTOOLS_SCM_PRETEND_VERSION supplies the declared private pin-derived version before VCS discovery; global form is required because hatch-vcs does not pass dist_name.',
            'Editable build requires reviewed editables~=0.3. Default non-exact mapping adds the owned source/src directory via path-only .pth; verify generated bytes after build.',
            'Generated src/hatch/_version.py is separate backend output, never a primary Git blob. Preserve exact original source inventory and generated-file delta.',
            'No license/network/year-dependent templates, setuptools migrations, external plugin/template acquisition, publishing or credentials in the approved first route.'
        ],approved_scope='Offline owned source build and version check, followed by synthetic built-in local metadata/new-project workflows only. Native Linux dependency wheels and exact runtime require separate review.'))
    print('Bound reviewed backend members and exact uv/setuptools hooks; no installation or target execution performed.')


if __name__=='__main__':main()
